def priority(path):
    if path == "":
        return "1.0"
    if path.startswith(("services", "foreigners")):
        return "0.9"
    if path in ("about/", "contact/"):
        return "0.8"
    if path == "privacy/":
        return "0.3"
    return "0.7"


def sitemap():
    urls = []
    for path in all_paths():
        lastmod = SITE["updated"]
        for p in POSTS:
            if path == f"blog/{p['slug']}/":
                lastmod = max(p["date"], SITE["updated"])
        alts = "".join(f'<xhtml:link rel="alternate" hreflang="{l}" href="{abs_url(l, path)}"/>' for l in LANGS)
        alts += f'<xhtml:link rel="alternate" hreflang="x-default" href="{abs_url(DEFAULT_LANG, path)}"/>'
        for l in LANGS:
            urls.append(f"<url><loc>{abs_url(l, path)}</loc>{alts}<lastmod>{lastmod}</lastmod><priority>{priority(path)}</priority></url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
            'xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' + "\n".join(urls) + "\n</urlset>\n")


