def render_blocks(blocks):
    out = []
    for kind, val in blocks:
        if kind == "p":
            out.append(f"<p>{e(val)}</p>")
        elif kind == "h2":
            out.append(f"<h2>{e(val)}</h2>")
        else:
            out.append(f"<{kind}>" + "".join(f"<li>{e(x)}</li>" for x in val) + f"</{kind}>")
    return "".join(out)


