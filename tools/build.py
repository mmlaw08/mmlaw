def _asset_version():
    """Changes whenever site.css or site.js change, so browsers never use a stale copy."""
    h = hashlib.sha1()
    for name in ("site.css", "site.js"):
        with open(os.path.join(ROOT, "assets", name), "rb") as f:
            h.update(f.read())
    return h.hexdigest()[:10]


