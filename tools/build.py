def clean_generated():
    """Remove previously generated HTML so deleted pages don't linger."""
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and d not in ("tools", "assets", "node_modules")
                       and "Desktop-html" not in d]
        for fn in filenames:
            if fn.endswith(".html"):
                fp = os.path.join(dirpath, fn)
                with open(fp, encoding="utf-8", errors="ignore") as f:
                    if GENERATED_MARK in f.read():
                        os.remove(fp)
        if dirpath != ROOT and not os.listdir(dirpath):
            os.rmdir(dirpath)


