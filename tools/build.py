def all_paths():
    paths = ["", "about/", "services/", "blog/", "contact/", "privacy/"]
    paths += [f"services/{s['slug']}/" for s in SERVICES]
    paths += [f"blog/{p['slug']}/" for p in POSTS]
    paths += ["foreigners/"] + [f"foreigners/{x['slug']}/" for x in FOREIGN_TOPICS]
